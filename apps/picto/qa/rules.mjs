// Run: node --experimental-strip-types apps/picto/qa/rules.mjs
import assert from 'node:assert/strict';
import module, { SCENE_COUNT, TOTAL_TASKS, RULESET_VERSION } from '../server/module.ts';

assert.equal(RULESET_VERSION,4);
assert.equal(SCENE_COUNT,70);
assert.equal(TOTAL_TASKS,70);
const players=Array.from({length:8},(_,i)=>({id:'player-'+i,name:'Игрок '+i}));
const kinds=new Set();
for(let session=0;session<25;session++){
 let state=module.createRoom({player:players[0],players:[players[0]]}).state;
 for(let n=1;n<players.length;n++)state=module.onJoin({state,player:players[n],players:players.slice(0,n+1)}).state;
 const savedSample={name:'Игрок 1',prompt:'Кот ищет ключ у дома.',board:[{id:'cat',x:40,y:40,r:0,s:1,frame:0}]};
 state=module.onMessage({state,player:players[0],players,payload:{type:'lexicon-import',entries:[savedSample]}}).state;
 assert.equal(state.lexicon.length,1,'Room owner can restore the shared phrasebook');
 state=module.onMessage({state,player:players[0],players,payload:{type:'start'}}).state;
 const order=[];
 const scenes=new Set();
 for(let round=0;round<8;round++){
  assert.equal(state.round,round+1);
  assert.equal(state.phase,'compose');
  const author=players[round],peer=players[(round+1)%players.length];
  assert.equal(state.author,author.id);
  assert.equal(state.choices.length,5);
  assert.deepEqual(state.choices.map(v=>v.length),[10,10,10,10,10]);
  assert.deepEqual(state.locationForms,[],'No redundant spatial preposition slot');
  assert.equal(state.solution.length,5);
  assert.equal(state.target.length,5);
  assert.equal(new Set(state.choices[0]).size,10);
  assert.equal(new Set(state.choices[2]).size,10);
  assert.equal(new Set(state.choices[4]).size,10);
  assert.equal(state.prompt,state.story);
  assert.ok(/затем/.test(state.prompt),'Each puzzle has a causal continuation');
  assert.ok(state.frames===2||state.frames===3);
  assert.equal(state.semanticVersion,4);
  assert.ok(state.target.every((v,i)=>Number.isInteger(v)&&v>=0&&v<state.choices[i].length));
  assert.equal(state.palette.length,112,'Full semantic alphabet is available');
  assert.equal(new Set(state.palette).size,state.palette.length);
  assert.deepEqual(state.blocked,[],'No artificial banned symbols');
  kinds.add(state.kind);order.push(state.kind);
  assert.equal(new Set(state.usedScenes).size,state.usedScenes.length,'A pack must not repeat in a game');
  const guest=module.onMessage({state,player:peer,players,payload:{type:'sync'}}).events[0].payload;
  assert.equal(guest.prompt,null);
  assert.deepEqual(guest.choices,[]);
  assert.deepEqual(guest.solution,[]);
  assert.deepEqual(guest.palette,[]);
  assert.equal(guest.story,null,'No leaked secret story before reveal');
  assert.equal(guest.lexicon.length,1);
  assert.ok(!('target' in guest),'Target indices must not leak through player events');
  const artist=module.onMessage({state,player:author,players,payload:{type:'sync'}}).events[0].payload;
  assert.equal(artist.prompt,state.prompt);
  assert.deepEqual(artist.palette,state.palette);
  assert.deepEqual(artist.blocked,state.blocked);
  assert.deepEqual(artist.solution,[]);
  const invalid=module.onMessage({state,player:author,players,payload:{type:'edit',glyphs:[{id:'unknown-glyph',x:50,y:50,r:0,s:1,frame:0}]}});
  assert.equal(invalid.state.board.length,0,'Unknown pictograms must be rejected server-side');
  const glyph={id:state.palette[0],x:42,y:51,r:0,s:1,frame:state.frames-1};
  state=module.onMessage({state,player:author,players,payload:{type:'edit',glyphs:[glyph]}}).state;
  assert.equal(state.board.length,1);
  assert.equal(state.board[0].frame,state.frames-1,'Board keeps the chosen story panel');
  state=module.onMessage({state,player:peer,players,payload:{type:'edit',glyphs:[]}}).state;
  assert.equal(state.board.length,1,'Only author can edit');
  state=module.onMessage({state,player:author,players,payload:{type:'publish'}}).state;
  assert.equal(state.phase,'compose','Empty storyboard panels must block publishing');
  const fullBoard=[glyph,...Array.from({length:state.frames-1},(_,i)=>({...glyph,x:60+i*7,frame:i}))];
  state=module.onMessage({state,player:author,players,payload:{type:'edit',glyphs:fullBoard}}).state;
  assert.equal(state.board.length,state.frames);
  state=module.onMessage({state,player:author,players,payload:{type:'publish'}}).state;
  assert.equal(state.phase,'guess');
  const bystander=module.onMessage({state,player:peer,players,payload:{type:'sync'}}).events[0].payload;
  assert.deepEqual(bystander.choices,state.choices);
  assert.deepEqual(bystander.locationForms,[]);
  assert.deepEqual(bystander.solution,[]);
  assert.equal(bystander.prompt,null);
  assert.ok(!('target' in bystander));
  state=module.onMessage({state,player:peer,players,payload:{type:'answer',cells:[null,null,null,null,null]}}).state;
  assert.equal(Object.keys(state.answers).length,0,'Cannot submit an empty answer');
  state=module.onMessage({state,player:peer,players,payload:{type:'answer',cells:[state.target[0],null,null,null,null]}}).state;
  assert.equal(state.answers[peer.id][0],state.target[0]);
  state=module.onMessage({state,player:peer,players,payload:{type:'answer',cells:state.target}}).state;
  assert.equal(state.answers[peer.id][1],null,'No second submissions');
  for(const player of players){
   if(player.id===author.id||player.id===peer.id)continue;
   state=module.onMessage({state,player,players,payload:{type:'answer',cells:[...state.target]}}).state;
  }
  assert.equal(state.phase,'reveal');
  assert.equal(state.history.at(-1).correct,31);
  assert.equal(state.history.at(-1).total,35);
  assert.equal(state.history.at(-1).points,62);
  if(round===0){state=module.onMessage({state,player:author,players,payload:{type:'save-word'}}).state;
   assert.equal(state.lexicon.length,2,'Author saves a scene after reveal');
   assert.deepEqual(state.lexicon.at(-1).board[0].frame,state.frames-1);}
  const revealed=module.onMessage({state,player:peer,players,payload:{type:'sync'}}).events[0].payload;
  assert.deepEqual(revealed.solution,state.solution);
  assert.equal(revealed.myAnswer[1],null);
  if(round<7)state=module.onMessage({state,player:players[0],players,payload:{type:'next'}}).state;
 }
 assert.equal(new Set(order.slice(0,6)).size,6,'All six semantic categories should appear every cycle');
 state=module.onMessage({state,player:players[0],players,payload:{type:'next'}}).state;
 assert.equal(state.phase,'results');
 assert.equal(state.wordsFound,248);
 assert.equal(state.attempts,280);
 assert.equal(state.score,496);
 assert.equal(state.history.length,8);
 assert.equal(state.lexicon.length,2,'Phrasebook survives a completed match');
}
assert.equal(kinds.size,6);
console.log('PICTO v4 rules OK: 70 curated causal stories, 112 glyphs, 2–3 frames, 5 semantic slots, shared lexicon, 25 complete 8-player matches.');
