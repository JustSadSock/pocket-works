import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {webcrypto} from 'node:crypto';

if(!globalThis.crypto)globalThis.crypto=webcrypto;
const source=await readFile(new URL('./server/module.ts',import.meta.url),'utf8');
const pinned=await readFile(new URL('../../pocketnet/module-versions/folio/v1.ts',import.meta.url),'utf8');
assert.equal(source,pinned,'immutable PocketNet v1 snapshot and module must match');
const {default:module,MIN_PLAYERS,MAX_PLAYERS,RULESET_VERSION}=await import('data:text/javascript,'+encodeURIComponent(source));
assert.equal(MIN_PLAYERS,1);assert.equal(MAX_PLAYERS,6);assert.equal(RULESET_VERSION,1);
const players=Array.from({length:6},(_,i)=>({id:'p'+i,name:'Artist '+i}));
let state=module.createRoom({player:players[0],payload:{title:'Our shared sheet',format:'portrait'}}).state;
assert.equal(state.doc.width,960);
assert.equal(state.doc.height,1280);
assert.equal(state.doc.title,'Our shared sheet');
assert.equal(state.protocol,1);
for(let i=1;i<6;i++)state=module.onJoin({state,players:players.slice(0,i+1)}).state;
assert.equal(state.players.length,6);
assert.throws(()=>module.onJoin({state,players:[...players,{id:'p6'}]}),/room_full/);
const put=(player,stroke)=>module.onMessage({state,player,payload:{type:'commit',stroke}});
const remove=player=>module.onMessage({state,player,payload:{type:'undo'}});
const again=player=>module.onMessage({state,player,payload:{type:'redo'}});
const stroke=id=>({id,layer:'shared',tool:'brush',brush:'ink',color:'#123456',size:8,opacity:1,points:[[2,3,1],[11,17,.75]]});
let result=put(players[0],stroke('stroke-unique-01'));state=result.state;
assert.equal(result.events[0].type,'op');
assert.equal(result.events[0].payload.revision,1);
assert.equal(result.events[0].payload.stroke.author,'p0');
assert.equal(state.doc.layers[0].strokes.length,1);
assert.equal(put(players[0],stroke('stroke-unique-01')).state.revision,1,'duplicate commits must be idempotent');
result=module.onMessage({state,player:players[1],payload:{type:'preview',stroke:stroke('preview-only-01')}});state=result.state;
assert.equal(result.events[0].type,'preview');
assert.equal(state.revision,1,'preview never mutates document');
assert.equal(state.doc.layers[0].strokes.length,1);
const fill={id:'fill-unique-01',layer:'shared',tool:'fill',color:'#ababab',opacity:1,bands:[[0,100,0,959]]};
result=put(players[0],fill);state=result.state;
assert.equal(result.events[0].type,'op');
assert.equal(state.doc.layers[0].strokes[0].tool,'fill','fills render beneath linework');
assert.equal(state.doc.layers[0].strokes[0].bands[0][1],100);
result=remove(players[0]);state=result.state;
assert.equal(result.events[0].payload.id,'fill-unique-01','undo uses commit order, not paint stack order');
assert.equal(state.doc.layers[0].strokes.length,1);
result=again(players[0]);state=result.state;
assert.equal(result.events[0].payload.stroke.id,'fill-unique-01');
assert.equal(state.doc.layers[0].strokes.length,2);
assert.equal(remove(players[1]).events[0].type,'notice','no artist can undo another artist');
const rejected=put(players[1],{...stroke('bad-unique-001'),points:[[9999,2,1]]});
assert.equal(rejected.events[0].type,'reject');
assert.equal(rejected.events[0].to,players[1].id);
assert.equal(state.doc.layers[0].strokes.length,2);
assert.equal(put(players[1],{...fill,id:'fill-bad-0001',bands:[[0,1281,0,959]]}).events[0].type,'reject');
result=module.onMessage({state,player:players[5],payload:{type:'sync'}});
assert.equal(result.events[0].to,'p5');
assert.deepEqual(result.events[0].payload.doc.layers[0].strokes,state.doc.layers[0].strokes,'join/reconnect snapshot is lossless');
state=module.onLeave({state,players:players.slice(1)}).state;
assert.equal(state.host,'p1','host handover preserves artwork');
assert.equal(state.doc.layers[0].strokes.length,2);
console.log('FOLIO shared protocol: 20+ checks passed (snapshot, caps, strokes, previews, dedup, fill, undo/redo, reconnect and validation)');
