import {test,expect} from '@playwright/test';
test('visual audit: six mages, own silhouette, different projectile and three-rune-chain workbench',async({page},testInfo)=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/apps/perekos/',{waitUntil:'domcontentloaded'});
 const original=await page.locator('#hero-preview').evaluate(c=>Array.from(c.getContext('2d').getImageData(0,0,c.width,c.height).data).join(','));
 await page.locator('#choose-mage').click();
 await expect(page.locator('#mage-select')).toBeVisible();
 await expect(page.locator('#mage-options .mage-option')).toHaveCount(6);
 await testInfo.attach('character-selector',{body:await page.screenshot(),contentType:'image/png'});
 await page.locator('#mage-options [data-mage="wire"]').click();
 await page.locator('#mage-confirm').click();
 await expect(page.locator('#chosen-mage-name')).toHaveText('Провод');
 const next=await page.locator('#hero-preview').evaluate(c=>Array.from(c.getContext('2d').getImageData(0,0,c.width,c.height).data).join(','));
 expect(next).not.toBe(original);
 await page.locator('#primary-action').click();
 await expect(page.locator('#controls')).toBeVisible();
 expect(await page.evaluate(()=>window.__perekosTest.state.actors[0].mageId)).toBe('wire');
 await expect(page.locator('#attack-name')).toHaveText('РАЗРЯД');
 await page.keyboard.down('Space');await page.waitForTimeout(160);await page.keyboard.up('Space');
 const shots=await page.evaluate(()=>window.__perekosTest.state.shots.filter(s=>s.owner===0).map(s=>s.style));
 expect(shots).toContain('bolt');expect(shots.filter(s=>s==='bolt').length).toBe(1);
 await testInfo.attach('bolt-in-arena',{body:await page.screenshot(),contentType:'image/png'});
 await page.evaluate(()=>{const s=window.__perekosTest.state;s.remaining=0.0001;s.actors[0].hp=8;s.actors[1].hp=95;window.__perekosTest.step()});
 await expect(page.locator('#draft')).toBeVisible();
 await expect(page.locator('#draft-title')).toContainText('Ничья');
 expect(await page.evaluate(()=>window.__perekosTest.state.score)).toEqual([0,0]);
 await page.locator('.rune-choice').first().click();
 await expect(page.locator('#build')).toBeVisible();
 await page.evaluate(()=>{const a=window.__perekosTest.state.actors[0];a.runes=['on_hurt','armor','on_cast','ball','on_dash','blink'];window.__perekosTest.reorder(0,0)});
 await expect(page.locator('.spell-lane')).toHaveCount(3);
 await expect(page.locator('.bench-slot')).toHaveCount(6);
 await testInfo.attach('three-spells-workbench',{body:await page.screenshot(),contentType:'image/png'});
 const sizing=await page.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth,slots:document.querySelector('#bench-slots').scrollHeight,visible:document.querySelector('#bench-slots').clientHeight}));
 expect(sizing.scroll).toBeLessThanOrEqual(sizing.width+1);
 expect(sizing.visible).toBeGreaterThan(0);
 expect(errors).toEqual([]);
});
