import {test,expect} from '@playwright/test';

test('battle command ledger navigates headquarters, tactical orders and units',async({page},info)=>{
  const errors:string[]=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/apps/palimpsest-atlas/',{waitUntil:'domcontentloaded'});
  await page.locator('[data-story="breitenfeld"]').click();
  await expect(page.locator('#command-toggle')).toBeVisible();
  await page.locator('#command-toggle').click();
  await expect(page.locator('#command-panel')).toBeVisible();
  await expect(page.locator('.command-group')).toHaveCount(3);
  await expect(page.locator('.command-unit')).toHaveCount(7);
  await page.locator('#next').click();
  await page.locator('#next').click();
  await expect(page.locator('#command-period')).toContainText('ФАЗА III');
  await expect(page.locator('#command-roster')).toContainText('Потеря строя');
  await page.screenshot({path:info.outputPath('01-phase-3-ledger.png')});
  await page.locator('.command-unit').filter({hasText:'Кавалерия Паппенгейма'}).click();
  await expect(page.locator('#command-panel')).toBeHidden();
  await expect(page.locator('#inspector')).toBeVisible();
  await expect(page.locator('#inspector-description')).toContainText('Штаб');
  await expect(page.locator('#inspector-description')).toContainText('Приказ');
  await expect(page.locator('#inspector-name')).toContainText('Паппенгейма');
  await page.screenshot({path:info.outputPath('02-formation-inspector.png')});
  await page.locator('#inspector-close').click();
  await page.locator('#command-toggle').click();
  await page.locator('#command-close').click();
  await expect(page.locator('#command-toggle')).toHaveAttribute('aria-expanded','false');
  expect(errors).toEqual([]);
});

test('battle authoring: five phases, headquarters, unit orders and polygon front line persist',async({page},info)=>{
  const errors:string[]=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/apps/palimpsest-atlas/',{waitUntil:'domcontentloaded'});
  await page.locator('#studio-new-battle').click();
  await expect(page.locator('#studio')).toBeVisible();
  await expect(page.locator('#studio-cursor-label')).toContainText('ФАЗА');
  await expect(page.locator('.studio-record')).toHaveCount(5);
  await page.locator('[data-studio-tab="commands"]').click();
  await page.locator('#studio-add').click();
  await page.locator('.editor-form [aria-label="Название штаба"]').fill('Штаб северной армии');
  await page.locator('.editor-form [aria-label="Название штаба"]').press('Tab');
  await page.locator('.editor-form [aria-label="Командующий"]').fill('Выдуманный командующий');
  await page.locator('.editor-form [aria-label="Командующий"]').press('Tab');
  await page.locator('.editor-form [aria-label="Сторона"]').selectOption('allied');
  await page.locator('[data-studio-tab="entities"]').click();
  await page.locator('#studio-add').click();
  await page.locator('.editor-form [aria-label="Название"]').fill('Северное крыло');
  await page.locator('.editor-form [aria-label="Название"]').press('Tab');
  await page.locator('.editor-form [aria-label="Тип"]').selectOption('army');
  await page.locator('.editor-form [aria-label="Подчиняется штабу"]').selectOption({label:'Штаб северной армии'});
  await page.locator('#studio-cursor').evaluate((input:HTMLInputElement)=>{
    input.value='3';
    input.dispatchEvent(new Event('input',{bubbles:true}));
    input.dispatchEvent(new Event('change',{bubbles:true}));
  });
  await page.locator('.orders-controls button').filter({hasText:'Добавить приказ'}).click();
  await page.locator('.orders-controls [aria-label="Тактическое действие"]').selectOption('reform');
  await page.locator('.orders-controls [aria-label="Пояснение / приказ"]').fill('Авторское перестроение левого крыла');
  await page.locator('.orders-controls [aria-label="Пояснение / приказ"]').press('Tab');
  await page.locator('[data-studio-tab="features"]').click();
  await page.locator('#studio-add').click();
  await page.locator('.editor-form [aria-label="Форма"]').selectOption('boundary');
  await expect(page.locator('.boundary-vertex')).toHaveCount(4);
  await page.screenshot({path:info.outputPath('03-border-editor.png')});
  await page.locator('.boundary-controls button').filter({hasText:'Добавить вершину'}).click();
  const map=await page.locator('#studio-map').boundingBox();
  if(!map)throw Error('Map canvas unavailable');
  await page.locator('#studio-map').click({position:{x:map.width*.48,y:map.height*.49}});
  await expect(page.locator('.boundary-vertex')).toHaveCount(5);
  await page.locator('#studio-save').click();
  await expect(page.locator('#studio-dirty')).toHaveText('СОХРАНЕНО');
  const saved=await page.evaluate(()=>{
    const data=JSON.parse(localStorage.getItem('pocket-works:palimpsest-atlas:stories:v1')||'{}');
    const story=data.stories[0];
    return {timeUnit:story.timeUnit,command:story.commands[0],order:story.entities[0].orders,
      border:story.features[0].points,events:story.events.length};
  });
  expect(saved.timeUnit).toBe('phase');
  expect(saved.events).toBe(5);
  expect(saved.command.name).toBe('Штаб северной армии');
  expect(saved.order[0].time).toBe(3);
  expect(saved.order[0].action).toBe('reform');
  expect(saved.border).toHaveLength(5);
  await page.locator('#studio-preview').click();
  await expect(page.locator('#story-title')).toHaveText('Новая тактическая реконструкция');
  await page.locator('#command-toggle').click();
  await expect(page.locator('.command-group')).toHaveCount(1);
  await page.screenshot({path:info.outputPath('04-authored-command-scene.png')});
  await page.reload({waitUntil:'domcontentloaded'});
  await expect(page.locator('#story-title')).toHaveText('Новая тактическая реконструкция');
  await expect(page.locator('#command-toggle')).toBeVisible();
  expect(errors).toEqual([]);
});
