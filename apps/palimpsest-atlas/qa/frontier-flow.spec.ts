import {test,expect} from '@playwright/test';

test('Breitenfeld frontier can be compared in overlay and split-date view',async({page},info)=>{
  const errors:string[]=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto('/apps/palimpsest-atlas/',{waitUntil:'domcontentloaded'});
  await page.locator('[data-story="breitenfeld"]').click();
  await page.locator('#next').click();await page.locator('#next').click();
  await expect(page.locator('#date-value')).toHaveText('3');
  await page.locator('#compare-toggle').click();
  await page.locator('#next').click();
  await expect(page.locator('#date-value')).toHaveText('4');
  await expect(page.locator('#compare-details')).toContainText('изменилось границ: 1');
  await expect(page.locator('#compare-split-guide')).toBeHidden();
  await page.locator('#compare-mode').click();
  await expect(page.locator('#compare-split-guide')).toBeVisible();
  await expect(page.locator('#compare-mode')).toHaveAttribute('aria-pressed','true');
  await page.locator('#compare-split').fill('68');
  await expect(page.locator('#compare-split-guide')).toHaveAttribute('style',/left: 68%/);
  await page.screenshot({path:info.outputPath('01-battle-border-compare-split.png')});
  await page.locator('#compare-mode').click();
  await expect(page.locator('#compare-split-guide')).toBeHidden();
  await expect(page.locator('#compare-details')).toContainText('изменилось границ: 1');
  await page.locator('#compare-mode').click();
  await page.locator('#compare-reset').click();
  await expect(page.locator('#comparison-banner')).toBeHidden();
  await expect(page.locator('#compare-split-guide')).toBeHidden();
  expect(errors).toEqual([]);
});

test('editor authors dated polygon shapes and navigable timeline, roundtrips through player',async({page},info)=>{
  const errors:string[]=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto('/apps/palimpsest-atlas/',{waitUntil:'domcontentloaded'});
  await page.locator('#studio-new-battle').click();
  await page.locator('#studio-title').fill('Пять фаз смены границы');
  await page.locator('#studio-title').press('Tab');
  await page.locator('[data-studio-tab="features"]').click();
  await page.locator('#studio-add').click();
  await page.locator('.editor-form [aria-label="Название на карте"]').fill('Внешний рубеж');
  await page.locator('.editor-form [aria-label="Название на карте"]').press('Tab');
  await page.locator('.editor-form [aria-label="Форма"]').selectOption('boundary');
  await expect(page.locator('.border-keyframe')).toHaveCount(1);
  await expect(page.locator('.boundary-vertex')).toHaveCount(4);
  await page.locator('#studio-cursor').evaluate((input:HTMLInputElement)=>{
    input.value='3';input.dispatchEvent(new Event('input',{bubbles:true}));
    input.dispatchEvent(new Event('change',{bubbles:true}));
  });
  await page.locator('.border-keyframe-actions button').filter({hasText:'Записать форму'}).click();
  await expect(page.locator('.border-keyframe')).toHaveCount(2);
  await page.locator('.boundary-vertex').first().click();
  await page.locator('.boundary-controls [aria-label="X вершины"]').fill('455');
  await page.locator('.boundary-controls [aria-label="X вершины"]').press('Tab');
  await page.locator('.boundary-controls [aria-label="Y вершины"]').fill('315');
  await page.locator('.boundary-controls [aria-label="Y вершины"]').press('Tab');
  await page.screenshot({path:info.outputPath('02-dated-border-editor.png')});
  await page.locator('#studio-track-toggle').click();
  await expect(page.locator('#studio-track-panel')).toBeVisible();
  await expect(page.locator('.track-lane')).toHaveCount(4);
  await expect(page.locator('.track-mark.track-frontiers')).toHaveCount(2);
  await page.locator('.track-mark.track-frontiers').nth(1).click();
  await expect(page.locator('#studio-cursor-label')).toContainText('ФАЗА III');
  await page.locator('#studio-save').click();
  await expect(page.locator('#studio-dirty')).toHaveText('СОХРАНЕНО');
  const snapshot=await page.evaluate(()=>{
    const data=JSON.parse(localStorage.getItem('pocket-works:palimpsest-atlas:stories:v1')||'{}');
    const item=data.stories[0].features[0];
    return {base:item.points,frames:item.boundaryFrames};
  });
  expect(snapshot.base).toHaveLength(4);
  expect(snapshot.frames).toHaveLength(1);
  expect(snapshot.frames[0].time).toBe(3);
  expect(snapshot.frames[0].points[0]).toEqual([455,315]);
  expect(snapshot.base[0]).not.toEqual(snapshot.frames[0].points[0]);
  await page.locator('#studio-preview').click();
  await expect(page.locator('#story-title')).toHaveText('Пять фаз смены границы');
  await page.locator('#compare-toggle').click();
  await page.locator('#next').click();await page.locator('#next').click();
  await expect(page.locator('#compare-details')).toContainText('изменилось границ: 1');
  await page.locator('#compare-mode').click();
  await expect(page.locator('#compare-split-guide')).toBeVisible();
  await page.screenshot({path:info.outputPath('03-authored-border-split-view.png')});
  await page.reload({waitUntil:'domcontentloaded'});
  await expect(page.locator('#story-title')).toHaveText('Пять фаз смены границы');
  await page.locator('#edit-story').click();
  await page.locator('[data-studio-tab="features"]').click();
  await expect(page.locator('.border-keyframe')).toHaveCount(2);
  expect(errors).toEqual([]);
});
