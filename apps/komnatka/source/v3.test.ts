import {describe,expect,it} from 'vitest';
import game,{RULESET_VERSION} from '../server/module.ts';
import v2,{RULESET_VERSION as PREVIOUS_VERSION} from '../../../pocketnet/module-versions/komnatka/v2.ts';
import pinnedV3 from '../../../pocketnet/module-versions/komnatka/v3.ts';
const host={id:'owner',name:'Хозяйка'},guest={id:'friend',name:'Гость'};
const setup=()=>{const s=game.createRoom({player:host}).state;game.onJoin({state:s,players:[host,guest]});return s;};
const send=(state:any,payload:any,player=host)=>game.onMessage({state,player,payload}) as any;
describe('PocketNet v3 backward-compatible rooms',()=>{
 it('pins immutable v2 alongside newest v3 and hides the memory solution during play',()=>{
  expect(PREVIOUS_VERSION).toBe(2);expect(v2.protocolVersion).toBe(1);
  expect(RULESET_VERSION).toBe(3);
  expect(pinnedV3.protocolVersion).toBe(1);
  const s=setup();
  send(s,{type:'start',mode:'memory',difficulty:'easy'});
  expect(s.difficulty).toBe('easy');
  expect(s.target.length).toBe(5);
  expect(s.targetFinishes).toBeTruthy();
  const preview=send(s,{type:'sync'},guest).events[0].payload;
  expect(preview.target).toHaveLength(5);
  expect(preview.targetFinishes).toBeTruthy();
  send(s,{type:'skip_preview'});
  const hidden=send(s,{type:'sync'},guest).events[0].payload;
  expect(hidden).not.toHaveProperty('target');
  expect(hidden).not.toHaveProperty('targetFinishes');
  send(s,{type:'finish'});
  const result=send(s,{type:'sync'},guest).events[0].payload;
  expect(result.target).toHaveLength(5);
  expect(result.targetFinishes).toBeTruthy();
  expect(result.score).toBeGreaterThanOrEqual(0);
  expect(result.score).toBeLessThanOrEqual(100);
 });
 it('starts a kitchen scenario with spatial rather than purchase-only goals',()=>{
  const s=setup();s.round=12;
  send(s,{type:'start',mode:'tenants',difficulty:'hard'});
  expect(s.purpose).toBe('kitchen');
  expect(s.difficulty).toBe('hard');
  expect(s.deadline-s.started).toBe(135000);
  const add=(item:any)=>send(s,{type:'add',item},guest);
  add({type:'diningtable',x:0,z:0,rot:0,material:'walnut'});
  expect(s.items[0]?.material).toBe('walnut');
  const table=s.items[0];
  add({type:'cutlery',x:0,z:0,rot:0,support:table.id,material:'ceramic'});
  add({type:'diningchair',x:-1.75,z:0,rot:0});
  add({type:'diningchair',x:1.75,z:0,rot:0});
  add({type:'kitchenunit',x:2.75,z:2.50,rot:0});
  const goals=send(s,{type:'sync'},guest).events[0].payload.goals;
  expect(goals).toHaveLength(4);
  expect(goals.every((g:any)=>g.done)).toBe(true);
  send(s,{type:'finish'});
  expect(s.score).toBe(100);
 });
 it('validates overlap, materials, finishes and real support relationships',()=>{
  const s=setup();send(s,{type:'start',mode:'tenants'});
  send(s,{type:'add',item:{type:'diningtable',x:0,z:0,rot:0,material:'velvet'}});
  expect(s.items).toHaveLength(1);
  send(s,{type:'add',item:{type:'stove',x:0,z:0,rot:0}});
  expect(s.items).toHaveLength(1);
  send(s,{type:'add',item:{type:'cutlery',x:1.8,z:1.8,rot:0}});
  expect(s.items).toHaveLength(1);
  send(s,{type:'add',item:{type:'cutlery',x:0,z:0,rot:0,support:s.items[0].id}});
  expect(s.items).toHaveLength(2);
  send(s,{type:'decorate',patch:{pattern:'plaster',patternLeft:'panel',floor:'terrazzo'}});
  expect(s.finishes.pattern).toBe('plaster');
  expect(s.finishes.patternLeft).toBe('panel');
  expect(s.finishes.floor).toBe('terrazzo');
 });
});
