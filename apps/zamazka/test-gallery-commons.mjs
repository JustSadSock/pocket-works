import assert from 'node:assert/strict';
import {galleryWindow} from './museum-motion.js';
import {boardPacket,paintBoardDelta} from './commons-board.js';
const order=[0,1,2,4,3];
assert.deepEqual(galleryWindow(order,0).map(x=>x.id),[4,3,0,1,2]);
assert.deepEqual(galleryWindow(order,4).map(x=>x.id),[2,4,3,0,1]);
const basic={k:'s2',q:0,c:'#aabbcc',s:9,p:[[0,0],[950,599]],revision:0};
assert.equal(boardPacket(basic),true);
assert.equal(boardPacket({...basic,p:[[961,0]]}),false);
assert.equal(boardPacket({...basic,p:[[0,601]]}),false);
assert.equal(boardPacket({...basic,p:[[NaN,40]]}),false);
assert.equal(boardPacket({...basic,p:Array.from({length:21},()=>[1,1])}),false);
assert.equal(boardPacket({...basic,s:200}),false);
assert.equal(boardPacket({...basic,c:'url(javascript:alert(1))'}),false);
assert.equal(boardPacket({...basic,k:'s/#invalid'}),false);
let paths=0,lines=0;
const ctx={beginPath(){paths++},moveTo(){},lineTo(){lines++},stroke(){},arc(){},fill(){}};
paintBoardDelta({getContext:()=>ctx},basic);
assert.equal(paths,1);assert.equal(lines,1);
const before=paths;paintBoardDelta({getContext:()=>ctx},{...basic,c:'invalid'});
assert.equal(paths,before);
console.log('PASS: five-frame gallery indexes, bounded real-time board packets and render path');
