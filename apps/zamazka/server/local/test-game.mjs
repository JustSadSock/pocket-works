// Complete synchronized two-person restoration, token ballot, verdict and reveal.
import {build} from 'esbuild';
import {dirname,join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {strict as assert} from 'node:assert';
const here=dirname(fileURLToPath(import.meta.url));
const result=await build({entryPoints:[join(here,'../module.ts')],bundle:true,platform:'node',target:'node22',format:'esm',write:false});
const loaded=await import('data:text/javascript;base64,'+Buffer.from(result.outputFiles[0].contents).toString('base64'));
assert.equal(loaded.MIN_PLAYERS,2);
assert.equal(loaded.RULESET_VERSION,2);
const game=loaded.default;
const a={id:'alice',name:'Алиса'},b={id:'bob',name:'Боб'},players=[a,b];
let state=game.createRoom({player:a,players:[a],payload:null}).state;
state=game.onJoin({state,player:b,players,payload:null}).state;
function act(player,type,args={}){
 const reply=game.onMessage({state,player,players,payload:{type,...args}});
 assert(reply?.state,'State lost after '+type);state=reply.state;return reply;
}
act(a,'start',{rounds:1});
assert.equal(state.phase,'preview');assert.equal(state.selected.length,5);
assert.equal(new Set(state.selected).size,5);
assert(state.selected.every(n=>n>0&&n<54));
assert(state.assignments.alice.variation>3,'damage seed must not repeat four fixed variants');
state.deadline=Date.now()-1;act(a,'pulse');assert.equal(state.phase,'drawing');
act(a,'submit',{strokes:[]});act(b,'submit',{strokes:[]});
assert.equal(state.phase,'voting');
let author=players[state.turn],judge=author.id===a.id?b:a;
let correctIndex=state.selected.indexOf(state.assignments[author.id].art);
let invalid=[0,0,0,0,0];invalid[correctIndex]=4;
const rejected=act(judge,'vote',{chips:invalid});
assert(rejected.events.some(e=>e.type==='notice'),'Ballot with four chips must be rejected');
assert.equal(state.phase,'voting');
let chips=[0,0,0,0,0];chips[correctIndex]=2;chips[(correctIndex+1)%5]=1;
act(judge,'vote',{chips});assert.equal(state.turn,1);
author=players[state.turn];judge=author.id===a.id?b:a;
correctIndex=state.selected.indexOf(state.assignments[author.id].art);
chips=[0,0,0,0,0];chips[correctIndex]=3;
act(judge,'vote',{chips});
assert.equal(state.phase,'verdict');
assert.equal(state.gallery,undefined);
const snapshot=act(a,'sync').events[0].payload;
assert.equal(snapshot.gallery.length,2);
assert.equal(snapshot.gallery[0].votes[judge.id] instanceof Array,false); // judge belongs to other turn
assert.equal(Object.keys(state.scores).length,2);
assert.equal(state.scores[players[0].id].eye+state.scores[players[1].id].eye,500);
assert.equal(state.scores[players[0].id].mask+state.scores[players[1].id].mask,50);
act(a,'advance');assert.equal(state.phase,'verdict','Cannot skip immediately after phase change');
state.deadline=Date.now()-1;act(a,'pulse');assert.equal(state.phase,'reveal');
state.deadline=Date.now()-1;act(a,'pulse');assert.equal(state.phase,'verdict');assert.equal(state.turn,1);
state.deadline=Date.now()-1;act(a,'pulse');assert.equal(state.phase,'reveal');
state.deadline=Date.now()-1;act(a,'pulse');assert.equal(state.phase,'results');
console.log('PASS: duo rules, randomized assignments, 3-token validation, 500 correct points, 50 artist points and 4-stage revelation');
