import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {runInNewContext} from 'node:vm';
import ts from 'typescript';
import {soundGalleryMarkup,SOUND_GALLERY} from '../sound-gallery.js';
import {MUSEUM_SOUND_EVENTS,MuseumAudio} from '../museum-audio.js';

let time=1_000_000;
class Clock extends Date{static now(){return time}}
const source=readFileSync(new URL('../server/module.ts',import.meta.url),'utf8');
const js=ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.CommonJS}}).outputText;
const exports={};
runInNewContext(js,{exports,Date:Clock,Math,Number,Array,Object,Map,Set,JSON,Error,console});
const game=exports.default;
assert.equal(exports.RULESET_VERSION,20,'pause is a separately pinned immutable ruleset');
const host={id:'host',name:'Куратор'},guest={id:'guest',name:'Гость'},third={id:'third',name:'Третий'};
const room=game.createRoom({player:host}).state,users=[host,guest,third];
assert.equal(room.resumable,true,'only new v21 rooms opt into persisted network pause');
game.onJoin({state:room,player:guest,players:users});
game.onJoin({state:room,player:third,players:users});
const send=(person,payload)=>game.onMessage({state:room,player:person,players:users,payload});
send(host,{type:'start',rounds:1,drawingSeconds:160});
assert.equal(room.phase,'preview');
time+=3000;
const leftover=room.deadline-time;
room.paused=true;room.pausedAt=time;room.pauseRemainingMs=leftover;room.onlineIds=[];
time+=180000;
send(guest,{type:'pulse'});
assert.equal(room.phase,'preview','expired wallclock cannot progress paused room');
assert.equal(room.deadline,1_025_000,'pause does not mutate the stored original deadline before resume');
const synced=send(guest,{type:'sync'}).events[0].payload;
assert.equal(synced.paused,true);
assert.equal(synced.pauseRemainingMs,leftover);
assert.equal(synced.onlineIds.length,0);
const blocked=send(guest,{type:'art_ready',round:room.round});
assert.equal(blocked.events[0].type,'notice','untrusted actions cannot advance paused match');
room.onlineIds=['guest','third'];
send(guest,{type:'claim_host'});
assert.equal(room.host,'guest','old offline curator can be replaced after one minute');
send(guest,{type:'kick_player',targetId:'host'});
assert.equal(room.participants.length,2,'absent curator can be removed without affecting live players');
assert.equal(room.assignments.host,undefined);
assert.equal(room.onlineIds.includes('host'),false);
assert.equal(room.participants.map(p=>p.id).join(','),'guest,third');
assert.equal(send(guest,{type:'kick_player',targetId:'third'}).events[0].type,'notice',
 'host may not kick connected player');
room.paused=false;room.deadline=time+room.pauseRemainingMs;room.pauseRemainingMs=null;
assert.equal(room.deadline-time,leftover,'remaining time resumes from unchanged value');
const later=room.deadline+1;time=later;
send(guest,{type:'pulse'});
assert.equal(room.phase,'drawing','normal deadline transitions resume after curatorship takeover');

const list=SOUND_GALLERY.flatMap(x=>x.items.map(item=>item[0]));
for(const name of MUSEUM_SOUND_EVENTS)assert(list.includes(name),'missing sound demo: '+name);
assert(list.includes('clock-demo'));
const html=soundGalleryMarkup();
for(const name of list)assert(html.includes('data-debug-sound="'+name+'"'),'missing labeled demo '+name);
const audio=readFileSync(new URL('../museum-audio.js',import.meta.url),'utf8');
assert.match(audio,/const level=\.085\+\.915\*Math\.pow\(progress,1\.34\)/,'clockwork must crescendo from quiet to fully audible');
assert.match(audio,/if\(nowMs>=clock\.duckUntil\)/,'alarms must override gradual clock level');
const muted=new MuseumAudio(false);
assert.equal(muted.play('time-up',true),false);
muted.dispose();
console.log('ZAMAZKA: offline pause preserves deadlines, host succession, kick guard, full labeled foley gallery, dynamic clock gain OK');
