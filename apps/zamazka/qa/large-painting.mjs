import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {runInNewContext} from 'node:vm';
import ts from 'typescript';
import {paintPackets,sendPainting} from '../draft-transfer.js';

let time=100000;
class FakeDate extends Date{static now(){return time}}
const raw=readFileSync(new URL('../server/module.ts',import.meta.url),'utf8');
const transpiled=ts.transpileModule(raw,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.CommonJS}}).outputText;
const exports={};
runInNewContext(transpiled,{exports,Date:FakeDate,Math,Array,Number,Object,Error,JSON,Set,Map,console});
assert.equal(exports.RULESET_VERSION,20);
const game=exports.default,a={id:'artist',name:'Artist'},b={id:'guest',name:'Guest'},players=[a,b];
const state=game.createRoom({player:a}).state;
game.onJoin({state,player:b,players});
const send=(p,payload)=>game.onMessage({state,player:p,players,payload});
send(a,{type:'start',rounds:1});
time=state.deadline+1;send(a,{type:'pulse'});
assert.equal(state.phase,'drawing');
const ass=state.assignments[a.id];
const art=Array.from({length:400},(_,n)=>({c:n%2?'#123456':'#abcdef',s:12,t:'brush',p:Array.from({length:30},(_,j)=>[+((n%80)*7+j*.1).toFixed(1),+(20+j*3.2).toFixed(1)])}));
assert.equal(art.reduce((s,x)=>s+x.p.length,0),12000);
const meta={round:state.round,art:ass.art,variation:ass.variation,strokes:art};
const sent=[];
const batch=sendPainting(packet=>{sent.push(packet);send(a,packet)}, {...meta,type:'draft_chunk',revision:'rlarge-1'});
assert.ok(batch.parts>=50&&batch.parts<=64,'large art must span many validated parts');
for(const pkt of sent)assert.ok(new TextEncoder().encode(JSON.stringify({wireVersion:1,type:'game_message',payload:pkt})).length<16384,'frame must stay below PocketNet limit');
assert.equal(state.drafts[a.id].length,400,'all strokes saved and acknowledged');
assert.deepEqual(JSON.stringify(state.drafts[a.id]),JSON.stringify(art),'no geometry lost');
const invalid=paintPackets({...meta,type:'draft_chunk',revision:'rlarge-2'});
const previous=JSON.stringify(state.drafts[a.id]);
send(a,invalid[0]);
assert.equal(state.draftAssemblies[a.id].prefix,invalid[0].strokes.length,'unchanged strokes share the committed prefix instead of duplicating data');
assert.equal(state.draftAssemblies[a.id].strokes.length,0,'no duplicate full painting in room state');
assert.equal(JSON.stringify(state.drafts[a.id]),previous,'incomplete replacement cannot overwrite last confirmed painting');
time=state.deadline+1;send(a,{type:'pulse'});
assert.equal(state.phase,'drawing','multipart grace prevents premature reveal');
time+=exports.FINAL_SUBMISSION_GRACE_MS;send(a,{type:'pulse'});
assert.equal(state.phase,'voting');
assert.equal(JSON.stringify(state.assignments[a.id].strokes),previous,'deadline uses last FULL image');

const state2=game.createRoom({player:a}).state;
game.onJoin({state:state2,player:b,players});
const send2=(p,payload)=>game.onMessage({state:state2,player:p,players,payload});
send2(a,{type:'start',rounds:1});
time=state2.deadline+1;send2(a,{type:'pulse'});
const a2=state2.assignments[a.id],meta2={round:state2.round,art:a2.art,variation:a2.variation,strokes:art};
const results=[];
for(const part of paintPackets({...meta2,type:'submit_chunk',revision:'rsubmit-1'}))results.push(send2(a,part));
assert.equal(state2.assignments[a.id].strokes.length,400,'manual submit does not truncate long painting');
assert.equal(JSON.stringify(state2.assignments[a.id].strokes),JSON.stringify(art));
assert.equal(results.at(-1).state.assignments[a.id].strokes.length,400);
const faulty=send2(b,{type:'draft_chunk',round:state2.round,art:state2.assignments[b.id].art,variation:state2.assignments[b.id].variation,revision:'rerror-1',parts:2,index:1,strokes:art.slice(0,2)});
assert.equal(faulty.events[0].type,'notice','out-of-order chunk rejected');
console.log('ZAMAZKA: large multipart submissions, 16 KiB transport, atomic backups, and timeout recovery OK');
