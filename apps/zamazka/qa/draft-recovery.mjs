import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {runInNewContext} from 'node:vm';
import ts from 'typescript';

let time=100000;
class FakeDate extends Date{static now(){return time}}
const source=readFileSync(new URL('../server/module.ts',import.meta.url),'utf8');
const transpiled=ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.CommonJS}}).outputText;
const exports={};
runInNewContext(transpiled,{exports,Date:FakeDate,Math,Array,Number,Object,Error,JSON,Set,Map,console});
const game=exports.default,host={id:'host',name:'Host'},friend={id:'friend',name:'Friend'},players=[host,friend];
const state=game.createRoom({player:host}).state;
game.onJoin({state,player:friend,players});
const send=(player,payload)=>game.onMessage({state,player,players,payload});
send(host,{type:'start',rounds:1});
time=state.deadline+1;send(host,{type:'pulse'});
assert.equal(state.phase,'drawing');
const assignment=state.assignments[host.id];
const line=[{c:'#123456',s:12,t:'brush',p:[[101,103],[109,115],[128,119]]}];
let result=send(host,{type:'draft',round:state.round,art:assignment.art,variation:assignment.variation,strokes:line});
assert.equal(result.events[0].type,'draft_saved');
assert.equal(result.events[0].to,host.id,'ack is private to its author');
assert.equal(state.drafts[host.id].length,1);
const own=send(host,{type:'sync'}).events[0].payload;
const other=send(friend,{type:'sync'}).events[0].payload;
assert.equal(own.mine.draft.length,1,'owner can recover remote draft');
assert.equal(other.mine.draft,null,'other participants cannot see another draft');
const invalid=send(host,{type:'draft',round:state.round-1,art:assignment.art,variation:assignment.variation,strokes:[]});
assert.equal(invalid.events[0].type,'notice');
assert.equal(state.drafts[host.id].length,1,'stale packet cannot erase saved version');
send(host,{type:'draft',round:state.round,art:assignment.art,variation:assignment.variation,strokes:[{...line[0],p:[[999,999]]}]});
assert.equal(state.drafts[host.id].length,1,'malformed packet cannot overwrite valid draft');
time=state.deadline+1;
send(friend,{type:'pulse'});
assert.equal(state.phase,'voting','timeout advances without a confirm click');
assert.deepEqual(JSON.stringify(state.assignments[host.id].strokes),JSON.stringify(line),'last server draft survives timeout');
assert.deepEqual(JSON.stringify(state.assignments[friend.id].strokes),JSON.stringify([]),'truly blank artist stays blank');
assert.equal(Object.keys(state.drafts).length,0,'backup is folded into final assignment and duplicate room storage is released');
console.log('ZAMAZKA: private draft, stale rejection, validation and timeout recovery OK');
