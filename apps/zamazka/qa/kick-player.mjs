import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {runInNewContext} from 'node:vm';
import ts from 'typescript';

const file=url=>readFileSync(new URL(url,import.meta.url),'utf8');
const source=file('../server/module.ts');
const exports={};
const transpiled=ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.CommonJS}}).outputText;
runInNewContext(transpiled,{exports,Date,Math,Array,Number,Object,Error,JSON,Set,Map,console});
const mod=exports.default;
assert.equal(exports.RULESET_VERSION,17);
const host={id:'curator',name:'Куратор'},guest={id:'guest',name:'Гость'},third={id:'third',name:'Третий'};
const players=[host,guest,third],state=mod.createRoom({player:host}).state;
mod.onJoin({state,player:guest,players});
mod.onJoin({state,player:third,players});
const send=(player,payload)=>mod.onMessage({state,player,players,payload});
assert.equal(state.participants.length,3);
const initialState=JSON.stringify(state);
assert.match(send(guest,{type:'kick_player',targetId:host.id}).events[0].payload,/куратор/i);
assert.equal(JSON.stringify(state),initialState,'ordinary guest has no moderation privileges');
assert.match(send(host,{type:'kick_player',targetId:host.id}).events[0].payload,/нельзя/i);
assert.match(send(host,{type:'kick_player',targetId:'unknown'}).events[0].payload,/нельзя/i);
assert.equal(JSON.stringify(state),initialState,'invalid target and self-kick do not mutate state');
send(guest,{type:'emblem',image:null});
send(guest,{type:'board_delta',revision:0,k:'ink1',q:0,c:'#445566',s:8,p:[[1,2],[3,4]]});
assert.equal(state.board.segments.length,1);
const kicked=send(host,{type:'kick_player',targetId:guest.id});
assert.equal(kicked.events.filter(e=>e.type==='player_kicked').length,1,'one ejection signal');
assert.equal(kicked.events.find(e=>e.type==='player_kicked').to,guest.id);
assert.deepEqual(JSON.stringify(state.participants.map(p=>p.id)),JSON.stringify([host.id,third.id]));
assert.equal(state.scores[guest.id],undefined,'removed scores');
assert.equal(state.emblems[guest.id],undefined,'removed seal');
assert.equal(state.board.segments.length,0,'discard kicked lobby drawings');
assert.equal(state.board.revision,1,'peers reset the canvas');
assert.ok(kicked.events.some(e=>e.type==='state'&&e.to===third.id),'remaining participants are updated');
assert.ok(!kicked.events.some(e=>e.type==='state'&&e.to===guest.id),'no active session for evicted guest');
assert.match(send(host,{type:'kick_player',targetId:guest.id}).events[0].payload,/уже вышел/i);
const kickedGuest=send(guest,{type:'board_delta',revision:1,k:'hack1',q:0,c:'#445566',s:8,p:[[1,2]]});
assert.match(kickedGuest.events[0].payload,/Матч уже начался/i,'evicted player loses access even before network layer detaches');
send(host,{type:'start',rounds:1});
assert.equal(state.phase,'preview','remaining two can start');
assert.match(send(host,{type:'kick_player',targetId:third.id}).events[0].payload,/только до начала/i,'no dangerous mid-round change');
assert.equal(state.participants.length,2,'active match roster preserved');
const app=file('../app.js'),hub=file('../../../pocketnet/hub.mjs'),node=file('../../../pocket-server/src/main.mjs'),local=file('../server/local/server.mjs');
assert.match(app,/data-action="kick-player"/,'curator button is in lobby list');
assert.match(app,/roomModuleVersion\.slice\(1\)\)>=14/,'older pinned rooms hide unsupported kick control');
assert.match(app,/client\.on\('room_kicked'/,'evicted browser reacts');
assert.match(app,/modal\('Исключить реставратора\?'/,'curator must confirm irreversible action');
assert.match(hub,/applyKicks\(room, result\.events \?\? \[\], player\.id\)/,'edge hub releases network seat');
assert.match(node,/roomBroadcast\(room, 'presence'/,'local PocketNet notifies peers');
assert.match(local,/target\.roomId=null/,'local stand-alone host revokes room seat');
console.log('ZAMAZKA: curator kick authorization, state cleanup, transport eviction, confirm UI and no mid-round kick OK');
