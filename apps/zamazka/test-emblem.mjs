import assert from 'node:assert/strict';
import {getSavedEmblem,storeEmblem,normalizeEmblemStrokes,paintEmblem,exportEmblem,EMBLEM_LIMITS} from './emblem.js';
const fakeStore=new Map();
const storage={getItem:k=>fakeStore.get(k)||null,setItem:(k,v)=>fakeStore.set(k,v)};
const strokes=[{c:'#382b23',s:7,p:[[0,0],[120,71],[239,143]]}];
const image='data:image/webp;base64,UklGRlRlc3Q=';
assert.equal(storeEmblem(strokes,image,storage),true);
assert.equal(getSavedEmblem(storage).image,image);
assert.deepEqual(getSavedEmblem(storage).strokes,strokes);
assert.deepEqual(normalizeEmblemStrokes([{c:'javascript:alert(1)',s:7,p:[[0,0]]}]),[]);
assert.deepEqual(normalizeEmblemStrokes([{c:'#112233',s:7,p:[[500,0]]}]),[]);
assert.deepEqual(normalizeEmblemStrokes(Array.from({length:EMBLEM_LIMITS.strokes+1},()=>strokes[0])),[]);
assert.equal(storeEmblem(strokes,'<svg onload=alert(1)>',storage),false);
assert.equal(storeEmblem(strokes,'data:image/svg+xml;base64,PHN2Zz4=',storage),false);
const calls=[];
const ctx={clearRect:(...a)=>calls.push(['clear',...a]),beginPath:()=>{},arc:()=>{},fill:()=>{},moveTo:()=>{},lineTo:()=>{},stroke:()=>{}};
const mock={width:120,height:72,getContext:()=>ctx,toDataURL:()=>image};
paintEmblem(mock,strokes);
assert.equal(calls[0][0],'clear');
const doc={createElement:()=>({...mock})};
assert.equal(exportEmblem(strokes,doc),image);
console.log('PASS: editable seals, persisted strokes, raster-only transport and limits');
