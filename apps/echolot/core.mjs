export function key(x,y){return x+','+y}
export function inside(x,y){return Number.isInteger(x)&&Number.isInteger(y)&&(x-6)**2+(y-6)**2<=36}
export function reveal(state,r){const set=new Set(state.known);for(let y=0;y<=12;y++)for(let x=0;x<=12;x++)if(inside(x,y)&&(x-state.x)**2+(y-state.y)**2<=r*r)set.add(key(x,y));return [...set]}
export function fresh(m){const s={x:m.home[0],y:m.home[1],oxygen:m.oxygen,hull:3,samples:[],known:[],turns:0,scans:0,result:'active',message:'Сонар готов. Найди три образца и вернись на базу.'};s.known=reveal(s,2);return s}
export function transition(m,old,action){
if(old.result!=='active')return old;
if(action.type==='move'&&(!Number.isInteger(action.dx)||!Number.isInteger(action.dy)||Math.abs(action.dx)+Math.abs(action.dy)!==1))return old;
if(action.type!=='move'&&action.type!=='scan')return old;
const s={...old,samples:[...old.samples],known:[...old.known],turns:old.turns+1};
if(action.type==='scan'){if(s.oxygen<3)return {...old,message:'Недостаточно кислорода для импульса.'};s.oxygen-=3;s.scans++;s.known=reveal(s,4);s.message='Импульс: новые отражения на карте.'}
else{const x=s.x+action.dx,y=s.y+action.dy;if(!inside(x,y))return {...old,message:'Граница зоны погружения.'};s.oxygen--;const k=key(x,y);if(m.rocks.some(([a,b])=>a===x&&b===y)){s.hull--;s.known=[...new Set([...s.known,k])];s.message='Удар о риф! Корпус повреждён.'}else{s.x=x;s.y=y;s.known=reveal(s,1);s.message='Движение. Следи за отражениями.';if(m.samples.some(([a,b])=>a===x&&b===y)&&!s.samples.includes(k)){s.samples.push(k);s.message='Образец поднят: '+s.samples.length+' из '+m.samples.length+'.'}}}
if(s.hull<=0){s.result='lost';s.message='Корпус разрушен. Рейс окончен.'}else if(s.samples.length===m.samples.length&&s.x===m.home[0]&&s.y===m.home[1]){s.result='won';s.message='Стыковка! Все образцы доставлены.'}else if(s.oxygen<=0){s.result='lost';s.message='Кислород исчерпан. Рейс окончен.'}return s
}
export function target(m,s){const remaining=m.samples.filter(([x,y])=>!s.samples.includes(key(x,y)));return remaining.sort((a,b)=>Math.hypot(a[0]-s.x,a[1]-s.y)-Math.hypot(b[0]-s.x,b[1]-s.y))[0]||m.home}
export function route(m,start,end){const q=[[start,[]]],seen=new Set([key(...start)]);for(let i=0;i<q.length;i++){const [[x,y],path]=q[i];if(x===end[0]&&y===end[1])return path;for(const [dx,dy] of [[0,-1],[1,0],[0,1],[-1,0]]){const nx=x+dx,ny=y+dy,k=key(nx,ny);if(inside(nx,ny)&&!seen.has(k)&&!m.rocks.some(([a,b])=>a===nx&&b===ny)){seen.add(k);q.push([[nx,ny],[...path,{type:'move',dx,dy}]]);}}}return null}
