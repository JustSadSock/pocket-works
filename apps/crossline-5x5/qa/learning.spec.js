import {test,expect} from '@playwright/test';

test('guided first duel completes with real movement, attack, shield and five-beat playback',async({page})=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/apps/crossline-5x5/',{waitUntil:'domcontentloaded'});
 await page.locator('#openRules').click();
 await expect(page.locator('#lessonPanel')).toBeVisible();
 await expect(page.locator('#lessonTitle')).toHaveText('Сдвинь фишку');
 await page.locator('[data-dir="up"]').click();
 await expect(page.locator('#planCount')).toHaveText('0 / 5');
 await page.locator('[data-dir="right"]').click();
 await expect(page.locator('#lessonTitle')).toHaveText('Прикажи атаковать');
 await page.locator('#attack').click();
 await page.locator('[data-dir="down"]').click();
 await page.locator('#attack').click();
 await expect(page.locator('#lessonTitle')).toHaveText('Подними щит');
 await page.locator('#shield').click();
 await page.locator('[data-dir="up"]').click();
 await page.locator('[data-dir="left"]').click();
 await expect(page.locator('#planCount')).toHaveText('5 / 5');
 await page.locator('#submit').click();
 await expect(page.locator('#modalTitle')).toHaveText('Пять шагов выполнены',{timeout:14000});
 await page.locator('#modalAlt').click();
 await expect(page.locator('#replay')).toBeVisible();
 await expect(page.locator('#replayAnalysis')).toBeVisible();
 expect(errors).toEqual([]);
});
test('annotations cycle and persist for a solo player after reopening',async({page})=>{
 await page.goto('/apps/crossline-5x5/',{waitUntil:'domcontentloaded'});
 await page.locator('#solo').click();
 await page.locator('[data-difficulty-choice="easy"]').click();
 const cell=page.locator('#board>.cell[data-x="1"][data-y="2"]');
 await cell.click();
 await expect(cell.locator('.arena-cell-mark')).toHaveText('•');
 await cell.click();
 await expect(cell.locator('.arena-cell-mark')).toHaveText('!');
 await page.locator('#pause').click();
 await page.locator('#modalThird').click();
 await page.locator('#resume').click();
 await expect(page.locator('#board>.cell[data-x="1"][data-y="2"] .arena-cell-mark')).toHaveText('!');
 await page.locator('#board>.cell[data-x="1"][data-y="2"]').click();
 await expect(page.locator('#board>.cell[data-x="1"][data-y="2"] .arena-cell-mark')).toHaveCount(0);
});
test('sound settings volume and mute persist across reloads; reduced-motion is functional',async({page})=>{
 await page.goto('/apps/crossline-5x5/',{waitUntil:'domcontentloaded'});
 await page.locator('#sound').click();
 await expect(page.locator('#arenaSettings')).toBeVisible();
 await page.locator('#settingsVolume').fill('35');
 await expect(page.locator('#volumeOutput')).toHaveText('35%');
 await page.locator('#settingsMute').click();
 await expect(page.locator('#settingsMute')).toHaveText('Включить звук');
 await page.locator('#settingsMotion').click();
 await expect(page.locator('html')).toHaveAttribute('data-motion','off');
 await page.locator('#settingsClose').click();
 await page.reload({waitUntil:'domcontentloaded'});
 await page.locator('#sound').click();
 await expect(page.locator('#settingsVolume')).toHaveValue('35');
 await expect(page.locator('#settingsMute')).toHaveText('Включить звук');
 await expect(page.locator('html')).toHaveAttribute('data-motion','off');
});
